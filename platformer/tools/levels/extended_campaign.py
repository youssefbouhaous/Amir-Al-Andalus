"""The advanced continuation chapter (levels 7-10).

The first six maps are deliberately not regenerated by this module. These
maps use the same authoring language but focus on combinations: switch
blocks plus crumbling floors, wind plus carpets, fountains plus wheels, and
night hazards layered over timed traversal.
"""

from tools.level_format import LevelDef, O, Segment, Terrain
from tools.levels.campaign import HEIGHT, Route


def _pads(route: Route, start: int, stop: int, step: int = 3, width: float = 3) -> None:
    """Build a forgiving lower crossing below an optional moving shortcut."""
    for x in range(start, stop, step):
        route.obj(x, 22.25, O("lily_pad", w=width, flower=(x - start) % 2 == 0))


def _finish(route: Route, number: int, name: str, subtitle: str, theme: str,
            music: str, terrain: Terrain, following: str | None,
            **properties: object) -> LevelDef:
    route.ground_obj(3, O("player_spawn"))
    route.ground_obj(route.width - 5, O("goal", style="sword" if following is None else "gate"))
    return LevelDef(
        f"level{number}.tmx", name, subtitle, theme, music, following or "",
        [Segment(["".join(row) for row in route.grid], objects=route.objects,
                 backdrops=route.backdrops)],
        terrain,
        {"par_time": 190 + (number - 7) * 40, "difficulty": number, **properties},
        seed=number * 41,
        height=HEIGHT,
    )


